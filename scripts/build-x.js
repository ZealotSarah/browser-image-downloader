const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
for (const [output, entry] of [["x-main.js", "x-capture.js"], ["x-content.js", "x.js"]]) {
  const source = ["video-lib.js", "x-lib.js", entry]
    .map(file => fs.readFileSync(path.join(root, file), "utf8")).join("\n");
  // Each execution world owns its parser; no cross-file global initialization.
  fs.writeFileSync(path.join(root, output),
    `/* Generated by node scripts/build-x.js. */\n(() => {\nconst globalThis = {};\n${source}\n})();\n`);
}
